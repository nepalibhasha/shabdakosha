def expand_brihat_abbreviation(value: str | None) -> str | None:
    value = normalize_text(value or "").strip()
    return BRIHAT_ABBREVIATIONS.get(value, value) if value else None


def expand_pragya_abbreviation(value: str | None) -> str | None:
    value = normalize_text(value or "").strip()
    if not value:
        return None
    if "/" in value:
        return "/ ".join(PRAGYA_ABBREVIATIONS.get(part.strip(), part.strip()) for part in value.split("/"))
    return PRAGYA_ABBREVIATIONS.get(value, value)
